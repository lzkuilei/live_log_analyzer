# -*- coding: utf-8 -*-
"""解析逻辑测试：多场直播、空新增粉丝数、跨年下播。"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))
from analyzer import parse_live_log

LOG = """2026-03-30 14:06:16\t主播“画祺”（房间号：111） 03-30 14:05:48 已开播
2026-03-30 14:06:16\t主播“画祺”实时数据（房间号：111），在线人数：0，总观看人数：0，点赞数：0，新增粉丝数：0
2026-03-30 14:16:16\t主播“画祺”实时数据（房间号：111），在线人数：5，总观看人数：30，点赞数：100，新增粉丝数：2
2026-03-30 15:00:00\t主播“画祺”实时数据（房间号：111），在线人数：8，总观看人数：60，点赞数：200，新增粉丝数：
2026-03-30 16:22:47\t主播“画祺”已下播（房间号：111），下播时间：03-30 16:22:37，直播时长：2小时16分49秒，本场直播总观看人数：3843，点赞数：19072，新增粉丝数：
2026-03-30 19:00:00\t主播“小李”（房间号：222） 03-30 18:59:00 已开播
2026-03-30 19:10:00\t主播“小李”实时数据（房间号：222），在线人数：3，总观看人数：10，点赞数：5，新增粉丝数：1
2027-01-01 00:30:00\t主播“小李”已下播（房间号：222），下播时间：01-01 00:29:00，直播时长：5小时30分，本场直播总观看人数：500，点赞数：900，新增粉丝数：10
"""

data, sessions = parse_live_log(LOG)
assert len(sessions) == 2, f"应识别 2 场直播，实际 {len(sessions)}"
assert len(data) == 4, f"应提取 4 条数据，实际 {len(data)}"

s1, s2 = sessions
# 场1 基础信息
assert s1["主播名"] == "画祺" and s1["房间号"] == "111"
assert s1["下播时间"].strftime("%m-%d %H:%M:%S") == "03-30 16:22:37"
assert s1["直播时长"] == "2小时16分49秒"
# 空新增粉丝数按 0
row3 = data[2]
assert row3["新增粉丝数"] == 0, "空新增粉丝数应为 0"
# 场2 相对时间基于自己的开播时间（不串场）
row_late = data[2]  # 画祺 15:00 的数据
assert row_late["主播名"] == "画祺"
assert abs(row_late["相对时间(分钟)"] - (15 * 60 + 0 - 14 * 60 - 5 - 48 / 60)) < 1, row_late["相对时间(分钟)"]
# 场2 跨年下播
assert s2["下播时间"].year == 2027, s2["下播时间"]
assert s2["主播名"] == "小李"
# 场1 下播时间没串给场2 数据行
row_xl = data[-1]
assert row_xl["主播名"] == "小李" and row_xl["直播时长"] == "5小时30分"

df = __import__("analyzer").build_dataframe(data)
assert len(df) == 4
print("全部测试通过 ✔")
print(df[["主播名", "日志时间", "在线人数", "新增粉丝数", "相对时间(分钟)", "直播时长"]].to_string())
