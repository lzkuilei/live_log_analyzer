# -*- coding: utf-8 -*-
"""解析逻辑测试：场次配对、重复开播合并、跨天归属、时间断层切场、空新增粉丝数、跨年下播。"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src"))
from analyzer import parse_live_log, build_dataframe

T = "\t"
LOG = "\n".join([
    f"2026-03-30 14:06:16{T}主播“画祺”（房间号：111） 03-30 14:05:48 已开播",
    f"2026-03-30 14:06:16{T}主播“画祺”实时数据（房间号：111），在线人数：0，总观看人数：0，点赞数：0，新增粉丝数：0",
    f"2026-03-30 15:00:00{T}主播“画祺”实时数据（房间号：111），在线人数：8，总观看人数：60，点赞数：200，新增粉丝数：",
    f"2026-03-31 00:30:00{T}主播“画祺”实时数据（房间号：111），在线人数：3，总观看人数：90，点赞数：300，新增粉丝数：5",
    f"2026-03-31 01:00:00{T}主播“画祺”已下播（房间号：111），下播时间：03-31 00:59:00，直播时长：10小时59分，本场直播总观看人数：100，点赞数：400，新增粉丝数：",
    f"2026-03-30 19:00:00{T}主播“小李”（房间号：222） 03-30 18:59:00 已开播",
    f"2026-03-30 19:10:00{T}主播“小李”实时数据（房间号：222），在线人数：3，总观看人数：10，点赞数：5，新增粉丝数：1",
    f"2026-03-30 19:40:00{T}主播“小李”（房间号：222） 03-30 19:39:00 已开播",  # 未下播再开播 → 重连
    f"2026-03-30 19:50:00{T}主播“小李”实时数据（房间号：222），在线人数：4，总观看人数：20，点赞数：8，新增粉丝数：2",
    f"2027-01-01 00:30:00{T}主播“小李”已下播（房间号：222），下播时间：01-01 00:29:00，直播时长：5小时30分，本场直播总观看人数：500，点赞数：900，新增粉丝数：10",
    f"2026-03-30 20:00:00{T}主播“阿强”实时数据（房间号：333），在线人数：4，总观看人数：20，点赞数：10，新增粉丝数：1",
    f"2026-03-30 20:30:00{T}主播“阿强”实时数据（房间号：333），在线人数：6，总观看人数：40，点赞数：30，新增粉丝数：2",
    f"2026-03-30 23:00:00{T}主播“阿强”实时数据（房间号：333），在线人数：9，总观看人数：70，点赞数：60，新增粉丝数：3",
])

data, sessions = parse_live_log(LOG)
df = build_dataframe(data)

# ---- 画祺：跨天直播，全场归属开播日 03-30，不拆成两天 ----
assert len(sessions) == 5, f"应识别 5 场，实际 {len(sessions)}"  # 画祺+小李+阿强×3
s_qi = sessions[0]
assert s_qi["主播名"] == "画祺"
assert s_qi["下播时间"].strftime("%m-%d %H:%M:%S") == "03-31 00:59:00"
assert s_qi["直播时长"] == "10小时59分"
rows_qi = df[df['主播名'] == '画祺']
assert set(rows_qi['直播日期']) == {rows_qi['直播日期'].iloc[0]}, "跨天数据应归属开播日"
assert len(rows_qi) == 3, f"画祺应有 3 条数据，实际 {len(rows_qi)}"
assert rows_qi['相对时间(分钟)'].iloc[-1] > 380

# ---- 小李：未下播就再次开播（断线重连）→ 仍是同一场，数据不丢 ----
s_li = sessions[1]
assert s_li["主播名"] == "小李"
assert s_li["下播时间"].year == 2027, "跨年下播自动进位"
assert len(df[df['主播名'] == '小李']) == 2, "重复开播期间的数据都归入同一场"

# ---- 阿强：无开播/下播线，间隔均超 10 分钟 → 断层切三场 ----
rows_q = df[df['主播名'] == '阿强']
sessions_q = [s for s in sessions if s['主播名'] == '阿强']
assert len(sessions_q) == 3, f"阿强三行间隔均超 10 分钟，应切成 3 场，实际 {len(sessions_q)}"
assert all(s['implicit'] for s in sessions_q), "无开播线的场次应标记为 implicit"
assert all(s['下播时间'] is None for s in sessions_q)

print("全部测试通过 ✔")
print(df.groupby(['主播名', '直播日期']).agg(条数=('在线人数', 'size')).to_string())
